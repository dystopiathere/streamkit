/**
 * Сетка раскладки: одна на редактор элементов и на места гостей.
 *
 * Шаг — в процентах кадра, а не в пикселях, потому что и позиции хранятся
 * процентами: у стримера с сорсом 1920 × 1080 и у стримера с 800 × 600 сетка
 * делит кадр одинаково. Десятая часть кадра — не произвольное число: по этим же
 * линиям идёт внутренняя безопасная зона (10 % от края), и «на одну клетку» —
 * ровно то, что раньше делал Shift со стрелкой.
 *
 * Shift означает одно и то же везде: по сетке. При перетаскивании — примагнитить
 * к ближайшей линии, со стрелкой — шагнуть на следующую линию.
 */
export const GRID_STEP = 10;

/** Ближайшая линия сетки. */
export function snapToGrid(value: number): number {
  return Math.round(value / GRID_STEP) * GRID_STEP;
}

/**
 * Следующая линия сетки в заданную сторону.
 *
 * Не «прибавить шаг»: от произвольной позиции прибавление шага никогда не
 * приводит на линию, и выровнять два элемента с клавиатуры было бы нельзя.
 * Значение ровно на линии сдвигается на клетку — иначе нажатие ничего не делало
 * бы. Дробь у деления снимается округлением: 30 % при шаге 10 обязано дать 40 и
 * 20, а не остаться на месте из-за 2.9999999999999996.
 */
export function stepToGrid(value: number, direction: number): number {
  const cell = Number((value / GRID_STEP).toFixed(6));
  const target = direction > 0 ? Math.floor(cell) + 1 : Math.ceil(cell) - 1;
  return target * GRID_STEP;
}
