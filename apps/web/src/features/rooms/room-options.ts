import type { RoomOptions } from 'livekit-client';

/**
 * Настройки комнаты для дашборда — и у стримера, и у гостя.
 *
 * В livekit-client обе выключены по умолчанию, и без них каждая плитка
 * размером с открытку получала бы верхний слой 720p каждого участника: комната
 * на четырёх гостей стоила бы серверу втрое больше исходящего трафика (расчёт —
 * docs/adr/0010).
 *
 * - `adaptiveStream` — подписчик получает слой под размер своего `<video>` и
 *   ничего, пока плитка не видна;
 * - `dynacast` — публикующий не кодирует слои, которые никто не смотрит.
 *
 * Объект вынесен в модуль, а не создаётся в компоненте: `LiveKitRoom` сравнивает
 * опции, и новый объект на каждый рендер пересоздавал бы комнату.
 */
export const ROOM_OPTIONS: RoomOptions = { adaptiveStream: true, dynacast: true };
