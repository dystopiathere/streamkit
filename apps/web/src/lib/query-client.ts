import { QueryClient } from '@tanstack/react-query';

/**
 * Кэш серверных данных дашборда.
 *
 * Вынесен из `App.tsx` в модуль, чтобы его могло чистить хранилище сессии: кэш
 * принадлежит ПОЛЬЗОВАТЕЛЮ, а не вкладке. Раньше выход гасил токен и оставлял
 * кэш на месте, и следующий вошедший в той же вкладке полминуты видел чужие
 * виджеты, чужие события с никами донатеров и чужой журнал согласий — а баннер
 * cookie принимал этот журнал за согласие нового человека.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // Данные дашборда меняются не каждую секунду, а рефетч при каждом
      // переключении вкладки во время стрима — лишняя нагрузка и мигание.
      staleTime: 30_000,
      refetchOnWindowFocus: false,
      retry: 1,
    },
  },
});
