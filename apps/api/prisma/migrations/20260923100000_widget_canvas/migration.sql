-- Окно виджета (`canvas`) — ширина и высота браузер-сорса, в которых рисуется
-- виджет. У новых виджетов по умолчанию 800×600.
--
-- Уже настроенным виджетам окно НЕ назначается: они рисовались во весь сорс, и
-- 800×600 увеличили бы весь текст у того, чей сорс 1920×1080, — прямо в эфире.
-- Явный null читается схемой как «окно не задано», а отсутствующий ключ —
-- как значение по умолчанию; поэтому ключ пишется, а не остаётся пустым.
UPDATE "Widget"
SET "configVersion" = 4,
    "config" = jsonb_set("config", '{canvas}', 'null'::jsonb, true)
WHERE jsonb_typeof("config") = 'object'
  AND NOT ("config" ? 'canvas');
