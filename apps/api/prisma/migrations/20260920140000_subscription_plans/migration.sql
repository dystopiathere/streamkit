-- Платные тарифы: «Мультистрим» и «Про».
--
-- До этой миграции тариф был один, и подписка отвечала только за приватные
-- комнаты. Теперь тарифов два, у них разные цены и разный состав, поэтому и у
-- подписки, и у платежа появляется тариф.
--
-- Значение по умолчанию PRO и оно же для существующих строк: всё, что оплачено
-- до появления тарифов, — это и есть «Про». Выставлять MULTISTREAM было бы
-- отнятием оплаченного доступа к комнатам.
CREATE TYPE "Plan" AS ENUM ('MULTISTREAM', 'PRO');

ALTER TABLE "Subscription" ADD COLUMN "plan" "Plan" NOT NULL DEFAULT 'PRO';
ALTER TABLE "Payment" ADD COLUMN "plan" "Plan" NOT NULL DEFAULT 'PRO';
