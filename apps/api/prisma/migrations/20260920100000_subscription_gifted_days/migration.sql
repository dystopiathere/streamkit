--
-- Нужны, чтобы снятие подарка не забирало оплаченное: из одного
-- `currentPeriodEnd` не видно, какие дни оплачены, а отнимать оплаченный
-- доступ нельзя — это обязательство по оферте. У существующих подписок ноль:
-- что из уже выданного было подарком, восстановить нечем, и лучше не снять
-- ничего, чем снять оплаченное.
ALTER TABLE "Subscription" ADD COLUMN "giftedDays" INTEGER NOT NULL DEFAULT 0;
