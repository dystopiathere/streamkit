import type { ConsentDocument } from '@prisma/client';

/**
 * Реестр юридических документов и их актуальных версий.
 *
 * Версия — это дата редакции; следующая редакция того же дня — с суффиксом `.2`,
 * `.3` (в шапке документа — «Редакция № 2», «№ 3»). Когда текст документа
 * меняется, здесь появляется новая версия: без этого реестра невозможно
 * доказать, на какую именно редакцию человек дал согласие.
 *
 * Что происходит с теми, кто согласился со старой редакцией, решает
 * `updatePolicy` документа, и ни в одном случае это не блокирует работу
 * сервиса: соглашение, оферту и политику пользователь принимает регистрацией и
 * пользованием, и об их изменениях его уведомляют; согласия по 152-ФЗ
 * (обработка ПДн, cookie) просят подтвердить заново, потому что молчание
 * согласием не является.
 *
 * Сами тексты лежат в apps/web/public/legal и отдаются фронтом; здесь только
 * метаданные.
 */
export interface LegalDocument {
  document: ConsentDocument;
  version: string;
  title: string;
  /** Путь на фронте, где опубликован текст. */
  path: string;
  /**
   * Опубликован ли документ. Неопубликованный не показывается в разделе
   * «Приватность» и не принимается: согласие на текст, которого нет, — не
   * согласие ни на что.
   */
  published: boolean;
  /** Обязателен ли документ для регистрации. */
  requiredOnRegister: boolean;
  /**
   * Что делать, когда выходит новая редакция.
   *
   * - `notify` — уведомить. Так поступают с документами, которые являются
   *   договором или информированием: соглашение и оферту пользователь принимает
   *   регистрацией и пользованием сервисом, порядок их изменения описан в самом
   *   соглашении; политика конфиденциальности — вообще не согласие, а
   *   обязательная к публикации информация (ст. 18.1 152-ФЗ), и «принимать» её
   *   нечем.
   * - `reconsent` — попросить подтвердить. Так поступают с документами, которые
   *   являются СОГЛАСИЕМ по 152-ФЗ: согласие обязано быть конкретным,
   *   информированным и однозначным, а молчание и бездействие согласием не
   *   являются. Новая редакция такого документа действует только с того
   *   момента, как человек её подтвердил; до тех пор обработка идёт по прежней.
   *
   * Ни то, ни другое не блокирует интерфейс: услуга оказывается по договору
   * (п. 5 ч. 1 ст. 6 152-ФЗ), и отказ подтвердить редакцию не повод отключать
   * человеку сервис. Разница только в том, о чём его просят: «ознакомьтесь» или
   * «подтвердите».
   */
  updatePolicy: 'notify' | 'reconsent';
  /**
   * Принимается только при оплате, а не кнопкой в разделе «Приватность».
   * Согласие на автоматические списания без выбора тарифа и суммы — не
   * согласие ни на что: человек не знает, сколько и когда с него спишут.
   */
  acceptedAtCheckout: boolean;
}

